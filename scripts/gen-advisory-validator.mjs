// Compiles each JSON schema in schema/ into a standalone ajv validator module.
// Workers forbid eval/new Function, so runtime ajv.compile() cannot run there.
//
//   npm run gen:schema              write every src/schema/*.validate.generated.js
//   npm run gen:schema -- --check   exit 1 if any committed file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGETS = [
  { schema: "schema/advisory.v1.json", out: "src/schema/advisory.validate.generated.js" },
  { schema: "schema/well-known.v1.json", out: "src/schema/well-known.validate.generated.js" },
];

function generate(schemaRel) {
  const schema = JSON.parse(readFileSync(resolve(root, schemaRel), "utf8"));
  const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);

  // ajv's ESM output still pulls its runtime helpers with require(). Turn each
  // one into an ESM import so the module loads in workerd. The helpers are
  // CommonJS (`exports.default = fn`, no __esModule flag). wrangler's esbuild
  // bundle imports them in Node mode, so the default import is the exports
  // object and the function is its `.default`; vite hands back the function
  // itself. Unwrap both, or every validation in the deployed worker throws.
  const imports = [];
  const body = standaloneCode(ajv, validate).replace(/require\("([^"]+)"\)\.default/g, (_, mod) => {
    const name = `ajvRuntime${imports.length}`;
    imports.push(`import ${name}Module from "${mod}.js";`, `const ${name} = ${name}Module.default ?? ${name}Module;`);
    return name;
  });
  if (body.includes("require(")) {
    console.error(`${schemaRel}: generated validator still calls require(); update the import rewrite`);
    process.exit(1);
  }
  return (
    `// GENERATED by scripts/gen-advisory-validator.mjs from ${schemaRel}. Do not edit.\n` +
    "// @ts-nocheck\n" +
    imports.map((l) => l + "\n").join("") +
    body +
    "\n"
  );
}

const check = process.argv.includes("--check");
let stale = 0;
for (const t of TARGETS) {
  const outPath = resolve(root, t.out);
  const code = generate(t.schema);
  if (check) {
    let current = "";
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      // missing file counts as stale
    }
    if (current !== code) {
      console.error(`${t.out} is stale. Run: npm run gen:schema`);
      stale++;
    }
  } else {
    writeFileSync(outPath, code);
    console.log(`wrote ${outPath}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("schema validators are up to date");
}
