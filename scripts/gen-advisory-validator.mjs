// Compiles schema/advisory.v1.json into a standalone ajv validator module.
// Workers forbid eval/new Function, so runtime ajv.compile() cannot run there.
//
//   npm run gen:schema              write src/schema/advisory.validate.generated.js
//   npm run gen:schema -- --check   exit 1 if the committed file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "schema/advisory.v1.json");
const outPath = resolve(root, "src/schema/advisory.validate.generated.js");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);

// ajv's ESM output still pulls its runtime helpers with require(). Turn each
// one into an ESM import so the module loads in workerd.
const imports = [];
const body = standaloneCode(ajv, validate).replace(/require\("([^"]+)"\)\.default/g, (_, mod) => {
  const name = `ajvRuntime${imports.length}`;
  imports.push(`import ${name} from "${mod}.js";`);
  return name;
});
if (body.includes("require(")) {
  console.error("generated validator still calls require(); update the import rewrite");
  process.exit(1);
}
const code =
  "// GENERATED by scripts/gen-advisory-validator.mjs from schema/advisory.v1.json. Do not edit.\n" +
  "// @ts-nocheck\n" +
  imports.map((l) => l + "\n").join("") +
  body +
  "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing file counts as stale
  }
  if (current !== code) {
    console.error("src/schema/advisory.validate.generated.js is stale. Run: npm run gen:schema");
    process.exit(1);
  }
  console.log("advisory validator is up to date");
} else {
  writeFileSync(outPath, code);
  console.log(`wrote ${outPath}`);
}
